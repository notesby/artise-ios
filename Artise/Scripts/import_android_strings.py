"""Converts an Artise Android module's string resources into iOS string files, keeping the keys.

Both apps then say the same thing. Run it again after the Android texts change.

Usage:
  import_android_strings.py <android res folder> <iOS resources folder> <table>
e.g.
  import_android_strings.py ../artise-android/artise/notes/impl/src/main/res Artise/Resources/Notes ArtiseNotes

values/ becomes en.lproj, values-es/ es.lproj, values-pt/ pt.lproj (any values-xx/ is xx.lproj).
<string> goes to <table>.strings and <plurals> to <table>.stringsdict. Each feature has its own table,
so its keys never clash with upstream's Localizable table.
"""
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

HEADER = """/*
 Copyright 2026 Artise.

 SPDX-License-Identifier: AGPL-3.0-only

 Generated by Artise/Scripts/import_android_strings.py from the Android app's strings. Edit them there.
*/
"""

PLIST_HEADER = """<?xml version="1.0" encoding="UTF-8"?>
<!--
 Copyright 2026 Artise.

 SPDX-License-Identifier: AGPL-3.0-only

 Generated by Artise/Scripts/import_android_strings.py from the Android app's strings. Edit them there.
-->
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
"""


def android_text(element):
    """The text Android shows: XML entities decoded, Android's backslash escapes and quotes resolved."""
    text = "".join(element.itertext())
    if len(text) >= 2 and text[0] == '"' and text[-1] == '"':
        text = text[1:-1]
    text = re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), text)
    return text


def ios_format(text):
    """Android's %1$s / %s become %1$@ / %@; numbers keep their %d."""
    return re.sub(r"%(\d+\$)?s", lambda m: "%" + (m.group(1) or "") + "@", text)


def escape_strings(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def escape_xml(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def convert(values_dir, lproj_dir, table):
    root = ET.parse(values_dir / "strings.xml").getroot()
    strings, plurals = [], []
    for element in root:
        if element.get("translatable") == "false" and values_dir.name != "values":
            continue
        name = element.get("name")
        if element.tag == "string":
            strings.append((name, ios_format(android_text(element))))
        elif element.tag == "plurals":
            items = {item.get("quantity"): ios_format(android_text(item)) for item in element.findall("item")}
            plurals.append((name, items))

    lproj_dir.mkdir(parents=True, exist_ok=True)
    lines = [HEADER] + [f'"{name}" = "{escape_strings(value)}";' for name, value in strings]
    (lproj_dir / f"{table}.strings").write_text("\n".join(lines) + "\n", encoding="utf-8")

    if plurals:
        parts = [PLIST_HEADER]
        for name, items in plurals:
            spec = re.search(r"%(\d+\$)?d", items.get("other", "")) or re.search(r"%(\d+\$)?d", next(iter(items.values())))
            parts.append(f"    <key>{name}</key>\n    <dict>\n")
            parts.append("        <key>NSStringLocalizedFormatKey</key>\n        <string>%#@count@</string>\n")
            parts.append("        <key>count</key>\n        <dict>\n")
            parts.append("            <key>NSStringFormatSpecTypeKey</key>\n            <string>NSStringPluralRuleType</string>\n")
            parts.append("            <key>NSStringFormatValueTypeKey</key>\n            <string>d</string>\n")
            for quantity, value in items.items():
                # The number is the plural's own argument; other arguments keep their positions.
                value = value.replace(spec.group(0), "%d") if spec else value
                parts.append(f"            <key>{quantity}</key>\n            <string>{escape_xml(value)}</string>\n")
            parts.append("        </dict>\n    </dict>\n")
        parts.append("</dict>\n</plist>\n")
        (lproj_dir / f"{table}.stringsdict").write_text("".join(parts), encoding="utf-8")
    return len(strings), len(plurals)


def main(res_dir, out_dir, table):
    for values_dir in sorted(res_dir.glob("values*")):
        if not (values_dir / "strings.xml").exists():
            continue
        language = "en" if values_dir.name == "values" else values_dir.name.split("-", 1)[1]
        count = convert(values_dir, out_dir / f"{language}.lproj", table)
        print(f"{language}: {count[0]} strings, {count[1]} plurals")


if __name__ == "__main__":
    main(pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), sys.argv[3])
